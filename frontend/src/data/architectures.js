/** 카드 ID와 실행 모드에 맞는 구조도 정의를 반환합니다. */
export function getArchitecture(id, mode = "local") {
  const profile = architectures[id];
  if (!profile) throw new Error(`Missing architecture: ${id}`);
  return { ...profile, nodes: profile.nodes.map((item) => ({ ...item, ...item.modes?.[mode] })) };
}
